package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"github.com/tesserix/onboarding-service/api/customercontract"
	"os"
	"path/filepath"
	"reflect"
	"strings"
)

func main() {
	output := flag.String("out", "../../contracts/customer-signup.ts", "generated contract path")
	check := flag.Bool("check", false, "verify generated output")
	flag.Parse()
	generated, err := generateContracts()
	if err == nil && *check {
		var current []byte
		current, err = os.ReadFile(*output)
		if err == nil && string(current) != generated {
			err = fmt.Errorf("customer signup contracts are stale; regenerate them")
		}
	} else if err == nil {
		if err = os.MkdirAll(filepath.Dir(*output), 0755); err == nil {
			err = os.WriteFile(*output, []byte(generated), 0644)
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generateContracts() (string, error) {
	out := "// Code generated by go run ./cmd/customercontract; DO NOT EDIT.\nimport { z } from \"zod\";\n\n"
	for _, contract := range []struct {
		name string
		kind reflect.Type
	}{
		{"CustomerBusinessAddress", reflect.TypeFor[customercontract.BusinessAddress]()},
		{"CustomerBusinessProfileView", reflect.TypeFor[customercontract.BusinessProfileView]()},
		{"CustomerOrganizationProfile", reflect.TypeFor[customercontract.OrganizationProfile]()},
		{"CustomerSignupInput", reflect.TypeFor[customercontract.Signup]()},
		{"CustomerSignupSigninInput", reflect.TypeFor[customercontract.SigninInput]()},
		{"CustomerSignupReceipt", reflect.TypeFor[customercontract.Receipt]()},
		{"CustomerSignupProof", reflect.TypeFor[customercontract.Proof]()},
		{"CustomerSignupDelivery", reflect.TypeFor[customercontract.Delivery]()},
		{"CustomerWorkspaceInput", reflect.TypeFor[customercontract.Workspace]()},
		{"CustomerLoginTargetInput", reflect.TypeFor[customercontract.LoginTargetInput]()},
		{"CustomerLoginTarget", reflect.TypeFor[customercontract.LoginTarget]()},
		{"CustomerIdentityProjectionInput", reflect.TypeFor[customercontract.IdentityProjectionInput]()},
		{"CustomerIdentityProjection", reflect.TypeFor[customercontract.IdentityProjection]()},
		{"CustomerSecurityView", reflect.TypeFor[customercontract.SecurityView]()},
		{"CustomerSecurityInput", reflect.TypeFor[customercontract.SecurityInput]()},
		{"CustomerSecurityRequest", reflect.TypeFor[customercontract.SecurityRequest]()},
	} {
		schema, err := contractSchema(contract.kind, "")
		if err != nil {
			return "", err
		}
		out += "export const " + contract.name + "Contract = " + schema + ";\nexport type " + contract.name + " = z.infer<typeof " + contract.name + "Contract>;\n\n"
	}
	return out, nil
}

func contractSchema(kind reflect.Type, choices string) (string, error) {
	if kind.Kind() == reflect.Pointer {
		return contractSchema(kind.Elem(), choices)
	}
	if kind.Kind() == reflect.Bool {
		return "z.boolean()", nil
	}
	if kind.Kind() == reflect.String {
		if values, ok := reflect.Zero(kind).Interface().(interface{ Values() []string }); ok {
			raw, err := json.Marshal(values.Values())
			if err != nil {
				return "", err
			}
			return "z.enum(" + string(raw) + ")", nil
		}
		if choices != "" {
			raw, err := json.Marshal(strings.Split(choices, ","))
			if err != nil {
				return "", err
			}
			return "z.enum(" + string(raw) + ")", nil
		}
		return "z.string()", nil
	}
	if kind.Kind() != reflect.Struct {
		return "", fmt.Errorf("unsupported customer contract kind %s", kind)
	}
	fields, err := contractFields(kind)
	if err != nil {
		return "", err
	}
	schema := "z.object({" + strings.Join(fields, ",") + "}).strict()"
	for i := range kind.NumField() {
		field := kind.Field(i)
		if when := field.Tag.Get("requireWhen"); when != "" {
			name := strings.Split(field.Tag.Get("json"), ",")[0]
			key, _ := json.Marshal(name)
			state, _ := json.Marshal(when)
			schema += ".superRefine((value,ctx)=>{if(value.state===" + string(state) + "&&!value[" + string(key) + "]){ctx.addIssue({code:'custom',path:[" + string(key) + "],message:'Complete initial workspace binding required'});}})"
		}
	}
	return schema, nil
}

func contractFields(kind reflect.Type) ([]string, error) {
	var fields []string
	for i := range kind.NumField() {
		field := kind.Field(i)
		if !field.IsExported() {
			continue
		}
		if field.Anonymous {
			nested, err := contractFields(field.Type)
			if err != nil {
				return nil, err
			}
			fields = append(fields, nested...)
			continue
		}
		tag := strings.Split(field.Tag.Get("json"), ",")
		if tag[0] == "-" {
			continue
		}
		if tag[0] == "" {
			return nil, fmt.Errorf("customer field %s lacks a JSON name", field.Name)
		}
		schema, err := contractSchema(field.Type, field.Tag.Get("enum"))
		if err != nil {
			return nil, err
		}
		if field.Tag.Get("format") == "email" {
			schema += ".email()"
		}
		if maximum := field.Tag.Get("max"); maximum != "" {
			schema += ".refine(value=>[...value].length<=" + maximum + ",{message:'Use up to " + maximum + " characters'})"
		}
		if field.Tag.Get("clean") == "true" {
			schema += ".refine(value=>value===value.trim()&&!/[\\u0000-\\u001f\\u007f-\\u009f]/.test(value),{message:'Use text without surrounding spaces or control characters'})"
		}
		if field.Tag.Get("nullable") == "true" {
			schema += ".nullable()"
		}
		if field.Tag.Get("format") == "uuid" {
			schema += ".uuid()"
		}
		if field.Tag.Get("required") == "true" && strings.HasPrefix(schema, "z.string()") {
			schema += ".min(1)"
		}
		if pattern := field.Tag.Get("pattern"); pattern != "" {
			raw, _ := json.Marshal(pattern)
			schema += ".regex(new RegExp(" + string(raw) + "))"
		}

		if len(tag) > 1 && tag[1] == "omitempty" {
			schema += ".optional()"
		}
		name, err := json.Marshal(tag[0])
		if err != nil {
			return nil, err
		}
		fields = append(fields, string(name)+":"+schema)
	}
	return fields, nil
}
