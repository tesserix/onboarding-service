package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"reflect"
	"strings"
	"time"

	"github.com/google/uuid"
	"github.com/tesserix/onboarding-service/api/internal/onboarding"
)

func main() {
	output := flag.String("out", "../../contracts/staff-recovery.ts", "generated consumer contract")
	check := flag.Bool("check", false, "check the retained artifact")
	flag.Parse()
	generated, err := generate()
	if err == nil && *check {
		var retained []byte
		retained, err = os.ReadFile(*output)
		if err == nil && !bytes.Equal(retained, generated) {
			err = fmt.Errorf("staff recovery contract is stale")
		}
	} else if err == nil {
		err = os.WriteFile(*output, generated, 0644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by onboarding-service/apps/api/cmd/staff-contracts. DO NOT EDIT.\n// Canonical source: Go JSON receipt definitions in internal/onboarding.\n\n")
	models := []any{onboarding.StaffIdentityReceipt{}, onboarding.StaffIdentityRecoverySourceReceipt{}, onboarding.StaffIdentityRecoveryProposalReceipt{}, onboarding.StaffIdentityRecoveryRequestReceipt{}, onboarding.StaffIdentityRecoveryDecisionReceipt{}}
	for _, model := range models {
		typ := reflect.TypeOf(model)
		fmt.Fprintf(&b, "export type %s = {\n", typ.Name())
		for _, field := range reflect.VisibleFields(typ) {
			tag := strings.Split(field.Tag.Get("json"), ",")
			if tag[0] == "" || tag[0] == "-" {
				return nil, fmt.Errorf("missing JSON contract for %s.%s", typ.Name(), field.Name)
			}
			optional := ""
			for _, option := range tag[1:] {
				if option == "omitempty" {
					optional = "?"
				}
			}
			valueType, err := typescriptType(field.Type)
			if err != nil {
				return nil, err
			}
			if field.Type.Kind() == reflect.Pointer && optional == "" {
				valueType += " | null"
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", tag[0], optional, valueType)
		}
		b.WriteString("};\n\n")
	}
	return []byte(b.String()), nil
}

func typescriptType(typ reflect.Type) (string, error) {
	if typ.Kind() == reflect.Pointer {
		return typescriptType(typ.Elem())
	}
	if typ == reflect.TypeFor[uuid.UUID]() || typ == reflect.TypeFor[time.Time]() {
		return "string", nil
	}
	switch typ.Kind() {
	case reflect.String:
		return "string", nil
	case reflect.Int:
		return "number", nil
	case reflect.Struct:
		return typ.Name(), nil
	default:
		return "", fmt.Errorf("unsupported staff contract type %s", typ)
	}
}
